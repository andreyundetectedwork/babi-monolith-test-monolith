// STATE
let currentLang = 'sr';
let currentCategory = 'mains';

// DOM ELEMENTS
document.addEventListener('DOMContentLoaded', () => {
    initLangButtons();
    initMobileDrawer();
    initMenuTabs();
    renderContent();
});

// LANGUAGE SWITCHING LOGIC
function initLangButtons() {
    const langBtns = document.querySelectorAll('.lang-btn');
    langBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            const lang = btn.getAttribute('data-lang');
            if (lang && lang !== currentLang) {
                currentLang = lang;
                
                // Update active state on all lang switchers
                document.querySelectorAll('.lang-btn').forEach(b => {
                    b.classList.toggle('active', b.getAttribute('data-lang') === lang);
                });

                renderContent();
            }
        });
    });
}

// RENDER ALL DYNAMIC UI
function renderContent() {
    // 1. Update i18n text nodes
    const dict = i18n[currentLang] || i18n.sr;
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (dict[key]) {
            el.textContent = dict[key];
        }
    });

    // 2. Render Menu Items
    renderMenu();

    // 3. Render Reviews
    renderReviews();
}

// MENU RENDER
function initMenuTabs() {
    const tabBtns = document.querySelectorAll('.menu-tabs .tab-btn');
    tabBtns.forEach(btn => {
        btn.addEventListener('click', () => {
            tabBtns.forEach(b => b.classList.remove('active'));
            btn.classList.add('active');
            currentCategory = btn.getAttribute('data-category');
            renderMenu();
        });
    });
}

function renderMenu() {
    const container = document.getElementById('menu-target');
    if (!container) return;

    const items = menuData[currentCategory] || [];
    container.innerHTML = items.map(item => `
        <div class="menu-item-card">
            <div class="item-header">
                <h3 class="item-name">${item.name[currentLang] || item.name.en}</h3>
                <span class="item-price">${item.price}</span>
            </div>
            <p class="item-desc">${item.desc[currentLang] || item.desc.en}</p>
        </div>
    `).join('');
}

// REVIEWS RENDER
function renderReviews() {
    const container = document.getElementById('reviews-target');
    if (!container) return;

    container.innerHTML = reviewsData.map(rev => `
        <div class="review-card">
            <div>
                <div class="review-author">
                    <div class="author-avatar">${rev.author.charAt(0)}</div>
                    <div class="author-info">
                        <h4>${rev.author}</h4>
                        <span>${rev.meta}</span>
                    </div>
                </div>
                <div class="review-rating">${'★'.repeat(rev.stars)}</div>
                <p class="review-text">"${rev.text[currentLang] || rev.text.en}"</p>
            </div>
        </div>
    `).join('');
}

// MOBILE MENU DRAWER
function initMobileDrawer() {
    const burgerBtn = document.getElementById('burger-btn');
    const drawer = document.getElementById('mobile-drawer');
    const drawerLinks = document.querySelectorAll('.drawer-link');

    if (!burgerBtn || !drawer) return;

    burgerBtn.addEventListener('click', () => {
        drawer.classList.toggle('open');
        document.body.style.overflow = drawer.classList.contains('open') ? 'hidden' : '';
    });

    drawerLinks.forEach(link => {
        link.addEventListener('click', () => {
            drawer.classList.remove('open');
            document.body.style.overflow = '';
        });
    });
}